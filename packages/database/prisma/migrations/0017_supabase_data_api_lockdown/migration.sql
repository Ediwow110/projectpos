-- Supabase exposes the public schema through its Data API by default.
-- NexPOS does not use Supabase Auth or the browser Data API; every database
-- operation goes through the server-side API and its PostgreSQL connection.
-- Enabling RLS with no public policies therefore closes direct anon/authenticated
-- row access while preserving access for the database owner used by the API.
--
-- Do not use FORCE ROW LEVEL SECURITY here: the server-side database owner
-- must continue to bypass RLS for the application's existing authorization
-- and tenant-isolation layer.

